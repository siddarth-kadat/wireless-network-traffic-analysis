"""E3: Data access repository for Detection_Result entries."""

import uuid as _uuid
from datetime import datetime
from typing import List, Optional

from sqlalchemy import select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from backend.src.database.models import Detection_Result
from backend.src.common.logger import get_logger

logger = get_logger(__name__)


class ResultRepository:
    """Read/write access for the Detection_Result entity.

    UUID mapping contract
    ----------------------
    result_uuid : UUID string supplied by E2 (result_id field in the
                  E3DetectionResultInput contract).  Never converted to an integer.
    result_id   : Auto-increment BigInteger primary key assigned by PostgreSQL.

    E3 detection-result input contract (E2 not yet implemented)
    ------------------------------------------------------------
    E3 expects E2 to supply the following fields:

        result_uuid      : str  — UUID4 generated by E2 (required)
        log_uuid         : str  — E1-generated log UUID (required, resolved to log_id)
        rule_id          : int  — Detection_Rule.rule_id integer (required)
        rule_match_status: bool — True = matched / suspicious (required)
        observed_value   : Optional[float]
        threshold_value  : Optional[float]
        detection_evidence: Optional[str]  — JSON-serialized evidence dict
        detection_time   : str  — ISO 8601 UTC timestamp (required)

    Transaction ownership lies with the calling service; this repository does
    NOT call session.commit().
    """

    def __init__(self, session: Session) -> None:
        self._session = session

    # ------------------------------------------------------------------
    # Create
    # ------------------------------------------------------------------

    def create(
        self,
        result_uuid: _uuid.UUID,
        log_id: int,
        rule_id: int,
        rule_match_status: bool,
        detection_time: datetime,
        observed_value: Optional[float] = None,
        threshold_value: Optional[float] = None,
        detection_evidence: Optional[str] = None,
    ) -> Detection_Result:
        """Persist a single Detection_Result record.

        Args:
            result_uuid: E2-generated UUID for this result.
            log_id: Internal BigInteger FK to traffic_logs.log_id.
            rule_id: Integer FK to detection_rules.rule_id.
            rule_match_status: True = rule matched (suspicious).
            detection_time: Timezone-aware detection datetime.
            observed_value: Optional observed metric value.
            threshold_value: Optional threshold used in detection.
            detection_evidence: Optional JSON-serialized evidence string.

        Returns:
            Flushed Detection_Result ORM instance (no commit).

        Raises:
            IntegrityError: If result_uuid already exists.
        """
        result = Detection_Result(
            result_uuid=result_uuid,
            log_id=log_id,
            rule_id=rule_id,
            rule_match_status=rule_match_status,
            detection_time=detection_time,
            observed_value=observed_value,
            threshold_value=threshold_value,
            detection_evidence=detection_evidence,
        )
        try:
            self._session.add(result)
            self._session.flush()
            logger.debug(
                "Created Detection_Result: result_id=%d, result_uuid=%s, matched=%s",
                result.result_id,
                result_uuid,
                rule_match_status,
            )
            return result
        except IntegrityError:
            self._session.rollback()
            raise

    # ------------------------------------------------------------------
    # UUID mapping helpers
    # ------------------------------------------------------------------

    def get_internal_id_by_uuid(self, result_uuid: _uuid.UUID) -> Optional[int]:
        """Resolve an external result UUID to its internal BigInteger primary key."""
        stmt = select(Detection_Result.result_id).where(
            Detection_Result.result_uuid == result_uuid
        )
        return self._session.scalars(stmt).first()

    def get_by_uuid(self, result_uuid: _uuid.UUID) -> Optional[Detection_Result]:
        """Return the Detection_Result ORM instance for a given result UUID."""
        stmt = select(Detection_Result).where(
            Detection_Result.result_uuid == result_uuid
        )
        return self._session.scalars(stmt).first()

    def exists_by_uuid(self, result_uuid: _uuid.UUID) -> bool:
        """Return True if a detection_result with the given UUID already exists."""
        stmt = select(Detection_Result.result_id).where(
            Detection_Result.result_uuid == result_uuid
        )
        return self._session.scalars(stmt).first() is not None

    # ------------------------------------------------------------------
    # Retrieve
    # ------------------------------------------------------------------

    def get_by_id(self, result_id: int) -> Optional[Detection_Result]:
        """Return a Detection_Result by its BigInteger primary key."""
        return self._session.get(Detection_Result, result_id)

    def list_by_log(
        self,
        log_id: int,
        offset: int = 0,
        limit: int = 100,
    ) -> List[Detection_Result]:
        """Return paginated detection results for a traffic log entry.

        Args:
            log_id: Internal BigInteger FK to traffic_logs.log_id.
            offset: Records to skip.
            limit: Maximum records to return (capped at 1000).

        Returns:
            List of Detection_Result ORM instances.
        """
        limit = min(limit, 1000)
        stmt = (
            select(Detection_Result)
            .where(Detection_Result.log_id == log_id)
            .order_by(Detection_Result.result_id)
            .offset(offset)
            .limit(limit)
        )
        return list(self._session.scalars(stmt).all())

    def list_matched(
        self,
        offset: int = 0,
        limit: int = 100,
    ) -> List[Detection_Result]:
        """Return paginated results where the detection rule matched.

        Args:
            offset: Records to skip.
            limit: Maximum records to return (capped at 1000).

        Returns:
            List of Detection_Result ORM instances with rule_match_status=True.
        """
        limit = min(limit, 1000)
        stmt = (
            select(Detection_Result)
            .where(Detection_Result.rule_match_status.is_(True))
            .order_by(Detection_Result.result_id)
            .offset(offset)
            .limit(limit)
        )
        return list(self._session.scalars(stmt).all())
